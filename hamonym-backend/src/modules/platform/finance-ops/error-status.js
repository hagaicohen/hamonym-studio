// Shared HTTP status mapping for Finance Operations controllers -- same
// "known business error codes map to a specific status, everything else is
// a logged 500" shape as billing-ops/error-status.js.
const STATUS_BY_CODE = {
 MASAV_INSTRUCTION_FINALIZED:409, MASAV_RESULTS_NOT_FINALIZED:409, MASAV_NO_RETRY_BALANCE:409, MASAV_RETRY_BALANCE_CONFLICT:409,
 INVALID_MASAV_RESULT:400, MASAV_RESULT_EXCEEDS_OUTSTANDING:409, MASAV_RESULT_REFERENCE_CONFLICT:409,
 MASAV_INSTRUCTION_NOT_FOUND:404, MASAV_RESULT_BALANCE_CONFLICT:409, MASAV_RESULT_UNRESOLVED_ATTEMPT:409,
  STATEMENT_NOT_FOUND: 404,
  EXCEPTION_NOT_FOUND: 404,
  PROPOSAL_NOT_FOUND: 404,

  MISSING_ADMIN_USER: 400,
  MISSING_REASON: 400,
  INVALID_RESOLUTION_TYPE: 400,
  MISSING_PROPOSAL_IDS: 400,
  INVALID_PROPOSAL_IDS: 400,
  DUPLICATE_PROPOSAL_IDS: 400,
  MASAV_EXPORT_SCHEMA_REQUIRED: 503,
  MASAV_PREVIEW_CHANGED: 409,
  MASAV_ALREADY_EXPORTED: 409,
  COLLECTION_HELD: 409,
  UNRESOLVED_COLLECTION_ATTEMPT: 409,
  STATEMENT_NOT_ACTIONABLE: 409,
  NO_ELIGIBLE_INSTRUCTIONS: 409,
  masav_not_configured: 409,
  masav_not_authorized: 409,
  masav_incomplete: 409,

  EXCEPTION_NOT_OPEN: 409,
  PROPOSAL_NOT_PROPOSED: 409,
  PROPOSAL_NOT_APPROVED: 409,
  PROPOSAL_STALE_AT_EXPORT: 409,
  NOT_AUTHORIZED: 409,
};

function statusFor(err) {
  return String(err.code || '').startsWith('MASAV_RETRY_BLOCKED_') ? 409 : STATUS_BY_CODE[err.code] || 500;
}

module.exports = { statusFor };
